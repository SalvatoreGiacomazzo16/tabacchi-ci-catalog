import { readdir, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const projectRoot = resolve(scriptDirectory, '..');
const productImagesDirectory = resolve(projectRoot, 'public', 'product-images');
const outputFile = resolve(projectRoot, 'src', 'data', 'generatedProductImageFilenames.ts');

const systemFileNames = new Set(['.DS_Store']);
const validImageExtension = /\.(png|jpe?g|webp|gif|avif|svg)$/i;
const excludedProductImageFilenames = new Set([
  'bambin-gesù-in-culla-celeste.png',
  'corno-grande-con-maschere.jpeg',
  'crocifisso-artigianale.png',
  'crocifisso-in-porcellana.jpeg',
  'maschera-del-silvano.jpeg',
  'maschera-della-sibilla.jpeg',
  'quadretto-bartolo-longo-in-porcellana.jpeg',
  'quadretto-di-gesù-in-porcellana.jpeg',
  'statuetta-asso-di-bastoni-con-maschera.jpeg',
  'statuetta-madonna-in-porcellana.jpeg',
  'statuetta-san-giuseppe-a-riposo.jpeg',
  'tondo-sacro-da-appoggio.png',
  'vesuvio-3-con-maschera.jpeg',
]);

function isValidImageFile(entry) {
  return (
    entry.isFile() &&
    !systemFileNames.has(entry.name) &&
    !excludedProductImageFilenames.has(entry.name) &&
    !entry.name.startsWith('._') &&
    validImageExtension.test(entry.name)
  );
}

const imageEntries = await readdir(productImagesDirectory, { withFileTypes: true });

const productImageFilenames = imageEntries
  .filter(isValidImageFile)
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, undefined, { numeric: true, sensitivity: 'base' }));

const fileContents = [
  '// This file is auto-generated by scripts/generate-product-image-filenames.mjs.',
  '// Do not edit manually.',
  '',
  'export const productImageFilenames = [',
  ...productImageFilenames.map((filename) => `  ${JSON.stringify(filename)},`),
  '] as const;',
  '',
  `export const productImageCount = ${productImageFilenames.length};`,
  '',
].join('\n');

await writeFile(outputFile, fileContents, 'utf8');

console.log(`Generated ${productImageFilenames.length} valid product image filenames.`);
